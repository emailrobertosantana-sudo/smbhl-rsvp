/* Turns your filled contacts.csv into SQL, with a random token_salt each.
   Runs entirely on your machine — no email address is sent anywhere.

   Usage:  node make-contacts-sql.js
   Output: contacts.sql  (then load it with the wrangler command it prints)
*/
const fs = require('fs');
const crypto = require('crypto');

const file = 'contacts.csv';
if (!fs.existsSync(file)) { console.error('contacts.csv not found in this folder.'); process.exit(1); }

// tolerant CSV read: handles quoted fields and both line endings
function parseCSV(text) {
  const rows = []; let row = [], cell = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i+1] === '"') { cell += '"'; i++; }
      else if (c === '"') q = false;
      else cell += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n') { row.push(cell); rows.push(row); row = []; cell = ''; }
    else if (c !== '\r') cell += c;
  }
  if (cell.length || row.length) { row.push(cell); rows.push(row); }
  return rows.filter(r => r.some(x => x.trim() !== ''));
}

const rows = parseCSV(fs.readFileSync(file, 'utf8'));
const head = rows.shift().map(h => h.trim().toLowerCase());
const col = n => head.indexOf(n);
for (const need of ['player_id','name','email','is_sub']) {
  if (col(need) < 0) { console.error('Missing column: ' + need); process.exit(1); }
}

const q = s => "'" + String(s == null ? '' : s).replace(/'/g, "''") + "'";
const out = ['-- generated by make-contacts-sql.js', 'BEGIN TRANSACTION;'];
let withEmail = 0, without = 0, subs = 0;
const seen = new Set();

for (const r of rows) {
  const id = r[col('player_id')].trim();
  const name = r[col('name')].trim();
  let email = r[col('email')].trim();
  const isSub = /^(1|yes|true|y)$/i.test(r[col('is_sub')].trim()) ? 1 : 0;
  if (!id) continue;
  if (seen.has(id)) { console.error('Duplicate player_id skipped: ' + id); continue; }
  seen.add(id);

  if (email && !/^[^@\s]+@[^@\s]+\.[^@\s]+$/.test(email)) {
    console.error('Looks wrong, kept anyway: ' + name + '  <' + email + '>');
  }
  email ? withEmail++ : without++;
  if (isSub) subs++;

  const salt = crypto.randomBytes(16).toString('hex');
  out.push(
    `INSERT INTO contacts (player_id,name,email,is_sub,token_salt) VALUES (` +
    `${q(id)},${q(name)},${email ? q(email) : 'NULL'},${isSub},${q(salt)}) ` +
    `ON CONFLICT(player_id) DO UPDATE SET name=excluded.name, email=excluded.email, is_sub=excluded.is_sub;`
  );
}
out.push('COMMIT;');
fs.writeFileSync('contacts.sql', out.join('\n') + '\n');

console.log('');
console.log('  contacts.sql written');
console.log('  ' + seen.size + ' people — ' + withEmail + ' with email, ' + without + ' without, ' + subs + ' subs');
console.log('');
console.log('  Load it with:');
console.log('    npx wrangler d1 execute smbhl-rsvp --remote --file=./contacts.sql');
console.log('');
